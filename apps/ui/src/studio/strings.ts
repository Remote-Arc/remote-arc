const reverse = new Map(Object.entries(STUDIO_EN).map(([zh, en]) => [en, zh]));
export function translateStudio(
  message: string,
  locale: "en" | "zh",
  ...values: (string | number)[]
): string {
  if (locale === "en" && /^恢复版本 \d+$/.test(message))
    return "Restored version " + message.replace("恢复版本 ", "");
  let result =
    locale === "en"
      ? (STUDIO_EN[message] ?? message)
      : (reverse.get(message) ?? message);
  values.forEach((value, index) => {
    result = result.replaceAll("{" + index + "}", String(value));
  });
  return result;
}
